'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OKF_DIR = path.join(ROOT, 'okf');
const OUT = path.join(OKF_DIR, 'index.json');

const SITE = {
  name: 'Quick Bytes',
  description:
    'Interview-prep notes on AI models and LLMs — what they are, their types, and real-world examples. Search a topic or explore the full guide.',
  url: 'https://kallolchakraborty.github.io/quick-bytes/',
  author: 'Kallol Chakraborty',
  authorUrl: 'https://www.linkedin.com/in/kallol-chakraborty-9728a699/',
};

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return {};
  const fm = {};
  m[1].split('\n').forEach(function (line) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) return;
    fm[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1').replace(/^\'(.*)\'$/, '$1').trim();
  });
  return fm;
}

const phases = [];
const todos = [];

(function walk(dir, rel) {
  fs.readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .forEach(function (entry) {
      if (entry.name === 'index.json') return;
      const abs = path.join(dir, entry.name);
      const fileRel = path.join(rel, entry.name);
      if (entry.isDirectory()) {
        walk(abs, fileRel);
        return;
      }
      if (!entry.name.endsWith('.md')) return;
      const fm = parseFrontmatter(fs.readFileSync(abs, 'utf8'));
      const type = fm.type || '';
      if (type === 'Phase') phases.push({ dir: abs, rel: fileRel, fm });
      else if (type === 'Guide') todos.push({ kind: 'guide', dir: abs, rel: fileRel, fm });
      else if (type === 'Section') todos.push({ kind: 'section', dir: abs, rel: fileRel, fm });
      else todos.push({ kind: 'skip', rel: fileRel, fm });
    });
})(OKF_DIR, 'okf');

function byOrder(fm, rel) {
  const n = parseInt(fm.order, 10);
  return isNaN(n) ? 2e9 : n;
}

const guideByDir = new Map();
todos
  .filter((t) => t.kind === 'guide')
  .sort((a, b) => byOrder(a.fm, a.rel) - byOrder(b.fm, b.rel))
  .forEach(function (g, i) {
    const guides = { id: g.fm.guide, title: g.fm.title, description: g.fm.description || '', icon: g.fm.icon || '', order: byOrder(g.fm, g.rel) };
    guideByDir.set(path.dirname(g.dir), guides);
  });

const phaseList = phases
  .sort((a, b) => byOrder(a.fm, a.rel) - byOrder(b.fm, b.rel))
  .map(function (p) {
    const phase = {
      id: p.fm.phase,
      title: p.fm.title,
      level: p.fm.level || '',
      description: p.fm.description || '',
      order: byOrder(p.fm, p.rel),
      guides: [],
    };
    guideByDir.forEach(function (guide, guideDir) {
      const sectionFiles = fs.readdirSync(guideDir).filter((n) => /\.md$/.test(n) && n !== 'index.md');
      const sections = sectionFiles
        .map(function (f) {
          const fm = parseFrontmatter(fs.readFileSync(path.join(guideDir, f), 'utf8'));
          return {
            id: fm.section,
            title: fm.title,
            icon: fm.icon || '',
            order: byOrder(fm, path.join(guideDir, f)),
            file: path
              .relative(ROOT, path.join(guideDir, f))
              .split(path.sep)
              .join('/'),
          };
        })
        .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
      guide.sections = sections;
      phase.guides.push(guide);
    });
    phase.guides.sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
    return phase;
  })
  .filter((p) => p.guides.length);

const out = {
  $note: 'Generated by scripts/build-manifest.js — do not edit. Run `npm run manifest`.',
  site: SITE,
  phases: phaseList,
};

fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
const nSections = phaseList.reduce((n, p) => n + p.guides.reduce((m, g) => m + g.sections.length, 0), 0);
console.log('okf/index.json written: %d phases, %d guides, %d sections', phaseList.length, phaseList.reduce((n, p) => n + p.guides.length, 0), nSections);